// Convert model research paper object to printable HTML
export function modelPaperToHtml(
  paper: ReturnType<typeof generateModelResearchReport>,
  datasetName: string,
  obsCount: number
): string {
  const sectionsHtml = paper.sections
    .map(
      (sec) => `
        <h2>${sec.heading}</h2>
        ${sec.paragraphs.map((p) => `<p>${p}</p>`).join('')}
        ${sec.equations ? sec.equations.map((eq) => `<div class="equation">${eq}</div>`).join('') : ''}
      `
    )
    .join('');

  return `
    <h1>${paper.title}</h1>
    <div class="meta-box">
      <strong>Dataset:</strong> ${datasetName} &nbsp;|&nbsp;
      <strong>Observations:</strong> ${obsCount} &nbsp;|&nbsp;
      <strong>Analytical Depth:</strong> ~${paper.wordCount} words &nbsp;|&nbsp;
      <strong>Model Category:</strong> Specialized Academic Empirical Report
    </div>
    ${sectionsHtml}
  `;
}

// Convert 2200+ words combined report to printable HTML
export function combinedReportToHtml(
  report: ReturnType<typeof generateCombinedConclusiveReport>,
  result: FullAnalysisResult
): string {
  const sectionsHtml = report.sections
    .map((sec) => {
      let tableHtml = '';
      if (sec.tableData && sec.tableData.length > 0) {
        const header = sec.tableData[0];
        const rows = sec.tableData.slice(1);
        tableHtml = `
          <table>
            <thead>
              <tr>${header.map((h) => `<th>${h}</th>`).join('')}</tr>
            </thead>
            <tbody>
              ${rows
                .map(
                  (r) => `<tr>${r.map((c, i) => `<td class="${i >= 3 ? 'num' : ''}">${c}</td>`).join('')}</tr>`
                )
                .join('')}
            </tbody>
          </table>
        `;
      }
      return `
        <h2>${sec.heading}</h2>
        ${sec.paragraphs.map((p) => `<p>${p}</p>`).join('')}
        ${tableHtml}
      `;
    })
    .join('');

  return `
    <h1>${report.title}</h1>
    <div class="meta-box">
      <strong>Subject Asset:</strong> ${result.datasetName} &nbsp;|&nbsp;
      <strong>Historical Range:</strong> ${result.stats.startDate} to ${result.stats.endDate} (${result.stats.count} observations) &nbsp;|&nbsp;
      <strong>Horizon:</strong> ${result.summary.horizonLabel} (${result.horizonSteps} steps) &nbsp;|&nbsp;
      <strong>Consensus Outlook:</strong> ${result.summary.marketBias} (${result.summary.confidenceGrade} Conviction) &nbsp;|&nbsp;
      <strong>Document Scope:</strong> Monograph Synthesis (~${report.wordCount} words)
    </div>
    ${sectionsHtml}
  `;
}

// Download handlers
export function downloadModelReportPdf(
  modelId: Exclude<ModelId, 'ensemble'> | 'volatility',
  result: FullAnalysisResult
) {
  const paper = generateModelResearchReport(modelId, result);
  const html = modelPaperToHtml(paper, result.datasetName, result.stats.count);
  downloadReportAsPdf(paper.title, html);
}

export function downloadModelReportWord(
  modelId: Exclude<ModelId, 'ensemble'> | 'volatility',
  result: FullAnalysisResult
) {
  const paper = generateModelResearchReport(modelId, result);
  const html = modelPaperToHtml(paper, result.datasetName, result.stats.count);
  const filename = `${safeSlug(result.datasetName)}_${modelId.toUpperCase()}_Academic_Research_Report`;
  downloadReportAsWord(paper.title, filename, html);
}

export function downloadCombinedReportPdf(result: FullAnalysisResult) {
  const report = generateCombinedConclusiveReport(result);
  const html = combinedReportToHtml(report, result);
  downloadReportAsPdf(report.title, html);
}

export function downloadCombinedReportWord(result: FullAnalysisResult) {
  const report = generateCombinedConclusiveReport(result);
  const html = combinedReportToHtml(report, result);
  const filename = `${safeSlug(result.datasetName)}_Comprehensive_Conclusive_Market_Report`;
  downloadReportAsWord(report.title, filename, html);
}
